    @Override
    public GradeReportDTO create(GradeReportDTO dto) {
        User student = userRepository.findById(dto.studentId())
                .orElseThrow(() -> new ResourceNotFoundException("Student not found with id: " + dto.studentId()));
        
        User generatedBy = userRepository.findById(dto.generatedById())
                .orElseThrow(() -> new ResourceNotFoundException("Generated by user not found with id: " + dto.generatedById()));

        Course course = null;
        if (dto.courseId() != null) {
            course = courseRepository.findById(dto.courseId())
                    .orElseThrow(() -> new ResourceNotFoundException("Course not found with id: " + dto.courseId()));
        }

        com.ohma.thutothebe.entity.Class classEntity = null;
        if (dto.classId() != null) {
            classEntity = classRepository.findById(dto.classId())
                    .orElseThrow(() -> new ResourceNotFoundException("Class not found with id: " + dto.classId()));
        }

        GradeReport report = reportMapper.toEntityWithReferences(dto, student, course, classEntity, generatedBy);
        beforeCreate(report);
        GradeReport savedReport = reportRepository.save(report);
        
        log.info("Created grade report with id: {} for student: {}", savedReport.getId(), student.getId());
        return reportMapper.toDto(savedReport);
    }

