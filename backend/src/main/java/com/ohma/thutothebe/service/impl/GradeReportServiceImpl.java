    @Override
    public GradeReportDTO generateStudentIndividualReport(Long studentId, Long courseId, Term term, 
                                                         Integer academicYear, Long generatedById) {
        // Calculate student's performance in the specific course
        List<Grade> grades = gradeRepository.findByStudentIdAndCourseIdAndActive(studentId, courseId, true);
        
        Double overallGrade = calculateOverallGrade(grades);
        Double overallPercentage = (overallGrade / 100.0) * 100;
        String gradeLetter = calculateGradeLetter(overallGrade);
        
        GradeReportDTO reportDTO = new GradeReportDTO(
                null, studentId, courseId, null, GradeReportType.STUDENT_INDIVIDUAL,
                term, academicYear, overallGrade, overallPercentage, gradeLetter,
                null, null, "Individual student performance report", generatedById,
                LocalDateTime.now(), null, true, null, null
        );
        
        return create(reportDTO);
    }

